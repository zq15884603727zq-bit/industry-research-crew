"""
Review Task — 审核修订任务（增强版）

驱动 Reviewer Agent 对报告初稿进行严格审核，输出结构化的审核报告和修订后报告。

与基础版的区别：
  - 审核维度按优先级排序（致命 > 严重 > 一般 > 轻微）
  - 输出严格分为两部分：审核报告 + 修订后报告
  - 每个问题要求标注位置、严重等级和修改方案
  - revised_report 必须是完整可交付的最终版本
"""

from crewai import Task, Agent


def create_review_task(agent: Agent, writing_task: Task) -> Task:
    """
    创建审核修订任务（增强版）。

    Args:
        agent:        Reviewer Agent 实例
        writing_task: 上游 Writing Task（报告初稿自动注入）

    Returns:
        CrewAI Task 实例
    """

    description = (
        "你已经收到了一份行业研究报告初稿（见上下文）。\n"
        "请执行严格的「三阶段审核流程」——不仅是挑错，更要给出可直接交付的最终版本。\n\n"
        "---\n\n"
        "## 第一阶段：逐章核查\n\n"
        "按以下顺序逐章阅读，发现每一个问题：\n\n"
        "### A. 逻辑一致性核查\n"
        "- [ ] 执行摘要的结论是否与正文各章节完全对齐？\n"
        "- [ ] 同一数据点在不同章节出现时数值是否一致？\n"
        "- [ ] 因果关系是否正确（如「因为需求增长，所以市场规模扩大」正确；\n"
        "  「因为市场规模扩大，所以需求增长」可能倒置）？\n"
        "- [ ] 论点与论据是否匹配（论据真的能支撑论点吗）？\n\n"
        "### B. 信息完整性核查\n"
        "- [ ] 是否覆盖了五大核心维度：市场规模、竞争格局、技术趋势、政策环境、风险分析？\n"
        "- [ ] 市场规模：是否包含具体数字、增长率、数据来源和时间？\n"
        "- [ ] 竞争格局：是否列出主要玩家、市场份额、竞争态势？\n"
        "- [ ] 趋势分析：是否有短期和中期的趋势判断？\n"
        "- [ ] 风险分析：是否区分了系统性风险和可规避风险？\n"
        "- [ ] 是否遗漏了重要的反面观点或不利因素？\n\n"
        "### C. 数据准确性核查\n"
        "- [ ] 关键数据是否标注了具体来源？\n"
        "- [ ] 数据呈现是否忠实于原始含义（没有夸大、曲解）？\n"
        "- [ ] 如果数据来自 Analyst 的分析（二手数据），是否已标注？\n"
        "- [ ] 百分比、增长率等基础计算是否无误？\n\n"
        "### D. 表达质量核查\n"
        "- [ ] 标题是否准确概括了章节核心内容？\n"
        "- [ ] 每段第一句话是否表达了该段的核心观点？\n"
        "- [ ] 是否有口语化、情绪化、过于夸张的表述需要替换？\n"
        "- [ ] 是否有超过 300 字的超长段落需要拆分？\n"
        "- [ ] 专业术语使用是否准确？\n\n"
        "### E. 格式规范核查\n"
        "- [ ] Markdown 标题层级是否正确（# → ## → ### → ####）？\n"
        "- [ ] 表格是否使用了正确的 Markdown 表格语法？\n"
        "- [ ] 加粗（**）、列表（-）使用是否恰当？\n\n"
        "---\n\n"
        "## 第二阶段：综合评分\n\n"
        "对五个维度分别打分（1-5 分），并给出总体评价：\n"
        "- 5 分：优秀，无需修改\n"
        "- 4 分：良好，有少量可优化之处\n"
        "- 3 分：合格，存在需要修改的问题\n"
        "- 2 分：不合格，存在严重缺陷\n"
        "- 1 分：不可交付，需要重写\n\n"
        "---\n\n"
        "## 第二阶段：输出审核报告 + 修订后报告\n\n"
        "### 审核报告（Review Report）格式：\n\n"
        "```markdown\n"
        "## 审核报告\n\n"
        "### 综合评分\n"
        "| 维度 | 评分 | 说明 |\n"
        "|------|------|------|\n"
        "| 逻辑一致性 | X/5 | ... |\n"
        "| 信息完整性 | X/5 | ... |\n"
        "| 数据准确性 | X/5 | ... |\n"
        "| 表达质量 | X/5 | ... |\n"
        "| 格式规范 | X/5 | ... |\n"
        "| **总评** | **X/5** | ... |\n\n"
        "### 发现的问题\n"
        "（按严重程度排序：致命 > 严重 > 一般 > 轻微）\n\n"
        "1. **[严重程度]** [章节/段落位置]\n"
        "   - 问题描述：...\n"
        "   - 修改建议：...\n"
        "   - 状态：[已修改 / 建议修改]\n"
        "```\n\n"
        "### 修订后报告（Revised Report）格式：\n\n"
        "```markdown\n"
        "## 修订后报告\n\n"
        "[从封面开始的完整 Markdown 报告，所有已修改的问题都已体现在报告中]\n"
        "```\n\n"
        "**重要：**\n"
        "- 修订后报告必须是完整的、可直接交付的最终版本\n"
        "- 所有标注「已修改」的问题必须在报告中体现修改\n"
        "- 不要输出「同原文」或「保持不变」——必须输出完整报告"
    )

    expected_output = (
        "严格按以下两部分输出：\n\n"
        "## 审核报告\n"
        "包含：综合评分表 + 逐条问题（含位置、严重等级、修改建议、修改状态）\n\n"
        "## 修订后报告\n"
        "包含：完整的、可直接交付的 Markdown 格式行业研究报告。\n"
        "所有审核发现的问题已在报告中修正。\n"
        "报告从封面开始，包含所有章节，不少于 2000 字。\n\n"
        "用中文输出。"
    )

    return Task(
        description=description,
        expected_output=expected_output,
        agent=agent,
        context=[writing_task],
    )
