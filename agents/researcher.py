"""
Research Agent — 行业研究员

负责调用搜索工具全面搜集指定行业的最新资料。
采用工厂函数设计，支持动态注入研究主题。
"""

from crewai import Agent
from config.settings import llm


def create_research_agent(topic: str = "", tools: list = None) -> Agent:
    """
    创建行业研究员 Agent。

    Args:
        topic:  研究主题（如 "AI芯片"、"新能源汽车"），会注入 Goal 中
        tools:  工具列表，后续传入搜索工具（SerperDevTool 等），先留空

    Returns:
        CrewAI Agent 实例

    设计要点：
        - allow_delegation=False：研究员不把任务推给其他 Agent
        - verbose=True：     打印推理过程，便于调试
        - max_iter=15：      给搜索和整理留出足够的迭代步数
    """

    # ── Role：身份标签，简洁精准 ────────────────────────────
    role = "行业研究员"

    # ── Goal：可执行的产出标准，{topic} 动态注入 ─────────────
    goal = (
        f"全面搜集「{topic}」行业的最新资料，覆盖以下维度：\n"
        "1. 市场动态与重大新闻（近 6 个月）\n"
        "2. 主要企业战略与竞争动作\n"
        "3. 政策法规与监管变化\n"
        "4. 技术突破与创新趋势\n"
        "5. 权威机构发布的行业报告关键数据\n\n"
        "输出要求：\n"
        "- 按主题分类整理\n"
        "- 每条信息注明来源和日期\n"
        "- 优先采纳权威信源（官方公告、权威媒体、咨询机构报告）\n"
        "- 为后续分析师提供充足、可靠的信息基础"
    )

    # ── Backstory：行为剧本，每句话暗示一种质量期望 ──────────
    backstory = (
        "你是一名拥有 10 年经验的资深行业研究员，曾在麦肯锡和高盛担任行业分析师。\n"
        "你的研究以严谨、全面、结构化著称。你擅长从海量信息中快速定位高价值内容，\n"
        "并通过多渠道交叉验证确保信息的准确性。你对信源的权威性极为敏感——\n"
        "会优先采用官方公告、权威媒体和知名咨询机构的报告，拒绝未经证实的小道消息。\n\n"
        "你有权使用 web_search（网络搜索）工具获取实时信息。\n"
        "你的工作流程（严格遵守）：\n"
        "1. 先用 1-2 个宽泛关键词扫描行业全景\n"
        "2. 再针对市场规模、竞争格局、政策 3 个核心维度各搜索 1 次\n"
        "3. 总共搜索 4-5 次后立即停止，进入整理阶段\n"
        "4. 对收集到的信息做去重和分类，标注来源和时效性\n\n"
        "重要规则：\n"
        "- 最多搜索 6 次，达到后必须输出最终结果\n"
        "- 如果已有足够信息覆盖 5 个维度，提前停止搜索\n"
        "- 不要让搜索结果堆砌，要及时整理输出\n\n"
        "记住：你的产出是整个研究链条的信息基础。"
        "如果你漏掉了关键信息或采信了不可靠的信源，\n"
        "后续的分析和报告都会建立在错误的基础上。"
    )

    return Agent(
        role=role,
        goal=goal,
        backstory=backstory,
        llm=llm,
        verbose=True,
        allow_delegation=False,
        max_iter=8,     # 限制搜索次数，避免上下文过大导致卡顿
        tools=tools or [],
    )
